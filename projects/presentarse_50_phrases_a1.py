def _phrases_for_block(start: int) -> list[tuple[int, str, str, str]]:
    return [phrase for phrase in PHRASES if start <= phrase[0] <= start + 4]

def _build_segments() -> list[dict]:
    import json
    import os
    manifest_path = "output/audio/tts/manifest.json"
    tts_durations = {}
    if os.path.exists(manifest_path):
        try:
            with open(manifest_path, encoding="utf-8") as f:
                data = json.load(f)
                for seg in data.get("segments", []):
                    tts_durations[int(seg["index"])] = float(seg["tts_duration_s"])
        except Exception:
            pass

    segments: list[dict] = [
        {
            "type": "intro",
            "text_es": "Hoy practicamos una rutina completa de presentación: desde hola hasta despedidas.",
            "duration_s": 14.0,
            "color_block": "neutral",
        }
    ]
    
    current_index = 2
    for block in BLOCKS:
        segments.append({
            "type": "block_header",
            "block_id": block["block_id"],
            "title_es": block["title_es"],
            "title_ko": block["title_ko"],
            "color_block": block["color_block"],
            "duration_s": 3.5,
        })
        current_index += 1
        
        for number, text_es, text_ko, example_es in _phrases_for_block(block["start"]):
            tts_dur = tts_durations.get(current_index, 0.0)
            dur = 12.0
            pause = 1.5
            
            if tts_dur > 0:
                # required = tts_dur + lead (0.2) + pause <= 12.05
                # Using 11.80 as a safe limit to avoid rounding issues that push the total above 12.05s
                max_allowed_pause = 11.80 - tts_dur
                if max_allowed_pause < 1.5:
                    pause = max(0.5, round(max_allowed_pause, 2))
                    
            segments.append({
                "type": "phrase",
                "frase_num": number,
                "text_es": text_es,
                "text_ko": text_ko,
                "example_es": example_es,
                "block_id": block["block_id"],
                "color_block": block["color_block"],
                "duration_s": dur,
                "repeat_pause_s": pause,
            })
            current_index += 1
            
    segments.append({
        "type": "outro",
        "text_es": "Muy bien. Repite estas 50 frases hasta que puedas presentarte con naturalidad.",
        "duration_s": 16.0,
        "color_block": "neutral",
    })
    return segments

